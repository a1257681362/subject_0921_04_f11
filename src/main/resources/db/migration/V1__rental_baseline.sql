-- ===========================================================================
-- V1 租车域基线（flyway-rental-1）
-- 背景：租车单相关表结构此前由 schema.sql 全量幂等脚本维护，无版本、无留档、
--       改动不可追溯，交接出现断点。本期起租车域 8 表移交 Flyway 版本管理。
-- 基线口径：本脚本 = 既有 schema.sql 在新建库上产出的租车域最终结构
--       （收编 rental-1 / rental-name-search-1 / rental-fsm-1 / photo-1 及
--       turnover-1 车辆网点列的演进结果），与存量库结构一致。
-- 执行口径：- 全部 IF NOT EXISTS 幂等写法：存量库逐条空转（自愈漂移），
--            新建库直接建表；升级失败事务回滚后可安全重跑；
--          - 本脚本一经执行即封存，禁止修改（validate-on-migrate 校验 checksum）；
--            后续结构变更一律新增更高版本脚本（V2__xxx.sql ...）。
-- 命名规范：V<递增整数版本号>__<小写描述，单词以下划线分隔>.sql。
-- ===========================================================================

-- 车辆台账
CREATE TABLE IF NOT EXISTS t_vehicle (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_no     VARCHAR(32)  NOT NULL,
    model        VARCHAR(64),
    status       VARCHAR(16)  NOT NULL DEFAULT 'IDLE',  -- IDLE 在库 / RENTING 出租中 / DISABLED 停用
    operator     VARCHAR(32)  NOT NULL,
    biz_time     TIMESTAMP    NOT NULL,
    request_no   VARCHAR(64)  NOT NULL,
    version      INT          NOT NULL DEFAULT 0,
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    branch_code  VARCHAR(32),                            -- 归属网点（turnover-1 引入；可空=未分派）
    CONSTRAINT uk_vehicle_plate UNIQUE (plate_no),
    CONSTRAINT ck_vehicle_status CHECK (status IN ('IDLE', 'RENTING', 'DISABLED'))
);

-- 租车单（全量记录，不做物理删除：已结算/已归档只许冲销）
CREATE TABLE IF NOT EXISTS t_rental_order (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no       VARCHAR(40)    NOT NULL,
    vehicle_id     BIGINT         NOT NULL,
    customer_name  VARCHAR(64)    NOT NULL,
    branch_code    VARCHAR(32),                    -- 归属网点（recon-1 对账按网点抽取，可空=未分派）
    status         VARCHAR(32)    NOT NULL DEFAULT 'CREATED',
    -- 状态机配置驱动（evops.rental.fsm）：默认 CREATED/RENTING/SETTLED/ARCHIVED/REVERSED。
    -- 新增状态只改配置不改代码、不改表结构，故此处不再以 CHECK 枚举锁死状态取值；
    -- 合法路径完全由状态机配置在应用层判定（越级/回退统一拒绝）。
    settle_amount  DECIMAL(12,2),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- 订单号库层唯一约束：拦截重复提交的最终兜底
    CONSTRAINT uk_rental_order_no UNIQUE (order_no)
);

-- 订单号 + 业务时间 组合检索
CREATE INDEX IF NOT EXISTS idx_rental_order_biz_time ON t_rental_order (biz_time);

-- 交接记录（交车 PICKUP / 还车 RETURN，均须登记油量表读数与车损照片）
CREATE TABLE IF NOT EXISTS t_rental_handover (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    type           VARCHAR(8)     NOT NULL,           -- PICKUP / RETURN
    fuel_reading   INT            NOT NULL,           -- 油量表读数（0-100，百分比）
    damage_photos  VARCHAR(1000)  NOT NULL,           -- 车损照片地址，多个以逗号分隔
    remark         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_handover_type CHECK (type IN ('PICKUP', 'RETURN')),
    CONSTRAINT ck_handover_fuel CHECK (fuel_reading BETWEEN 0 AND 100)
);

CREATE INDEX IF NOT EXISTS idx_handover_order ON t_rental_handover (order_id);

-- 订单事件流水：下单/交车/还车结算/归档/冲销 全部留痕；
-- 通用流转动作名取状态机配置（可扩展），故 event_type 不设 CHECK 枚举。
CREATE TABLE IF NOT EXISTS t_rental_order_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    event_type     VARCHAR(32)    NOT NULL,           -- CREATE/PICKUP/RETURN/ARCHIVE/REVERSE/RENAME 及配置新增动作
    detail         VARCHAR(500),
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_event_order ON t_rental_order_event (order_id);

-- 状态流转历史（交车生命周期审计链）：每次成功流转在业务事务内落一行。
-- 动作/状态为字符串、不设 CHECK：新增状态只改状态机配置，不改表结构。
-- 与事件流水分工：event 记业务动作叙述，transition 结构化记录每次状态变化，
-- 可按动作、起止状态、版本、关联交接、操作人/业务时间/请求号逐条追溯。
CREATE TABLE IF NOT EXISTS t_rental_order_transition (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    action         VARCHAR(32)    NOT NULL,           -- 流转动作（状态机配置 action）
    from_status    VARCHAR(32)    NOT NULL,           -- 起始状态
    to_status      VARCHAR(32)    NOT NULL,           -- 目标状态
    from_version   INT            NOT NULL,           -- 流转前订单版本（乐观锁）
    to_version     INT            NOT NULL,           -- 流转后订单版本
    handover_id    BIGINT,                            -- 关联交接记录（交车/还车；纯状态动作为空）
    remark         VARCHAR(500),                      -- 现场备注/原因（如冲销原因）
    operator       VARCHAR(32)    NOT NULL,
    biz_time       TIMESTAMP      NOT NULL,
    request_no     VARCHAR(64)    NOT NULL,
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_order_transition_order ON t_rental_order_transition (order_id, id);

-- 租车单客户姓名拼音索引（rental-name-search-1）
-- 派生索引数据：与订单一一对应（order_id 即主键），下单/改名在同一业务事务内同步，
-- 另提供全量重建与启动自愈。索引行不随行业务四要素，业务动作留痕见 t_rental_order_event。
-- 统一存无分隔符小写串：full_pinyin 逐字全拼（多音字取常用首读，非汉字原样保留），
-- initials 逐字拼音首字母；customer_name 冗余原文，支持中文/外文字母直查。
CREATE TABLE IF NOT EXISTS t_rental_order_name_index (
    order_id         BIGINT       NOT NULL,
    customer_name    VARCHAR(64)  NOT NULL,
    normalized_name  VARCHAR(64),             -- NFKC+小写+去标点后的姓名，支持中文/外文字母直查
    full_pinyin      VARCHAR(512),
    initials         VARCHAR(64),
    create_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_rental_order_name_index PRIMARY KEY (order_id)
);

-- 入口幂等请求记录（request_no 库层唯一，重复提交在此拦截）
CREATE TABLE IF NOT EXISTS t_idempotent_request (
    request_no     VARCHAR(64)    PRIMARY KEY,
    status         VARCHAR(16)    NOT NULL,           -- PROCESSING / DONE / FAILED
    operator       VARCHAR(32),
    response_body  CLOB,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_idempotent_status CHECK (status IN ('PROCESSING', 'DONE', 'FAILED'))
);

-- 交车照片标识（photo-1）：原图留存 / 后台异步处理 / 280px 水印预览图对外
-- 一订单一张照片一行，(order_id, file_hash) 唯一，同订单重复上传同一文件幂等；
-- 状态机 PENDING -> PROCESSING -> DONE / FAILED，FAILED 可重试（retry_count 累计）；
-- order_no / branch_code 为上传时快照（水印内容：网点标识 + 订单号），不随单回改。
CREATE TABLE IF NOT EXISTS t_handover_photo (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    order_no       VARCHAR(40)    NOT NULL,           -- 冗余订单号（水印内容），上传时快照
    branch_code    VARCHAR(32),                       -- 归属网点快照（可空=未分派，水印以 NO-BRANCH 占位）
    file_name      VARCHAR(128)   NOT NULL,           -- 上传原始文件名
    file_hash      VARCHAR(64)    NOT NULL,           -- 原图 SHA-256，同订单重复上传幂等键
    original_path  VARCHAR(500)   NOT NULL,           -- 原图落盘路径（仅内部留存，不对外）
    preview_path   VARCHAR(500),                      -- 280px 预览图路径（对外唯一出口，已摆正+水印）
    status         VARCHAR(10)    NOT NULL DEFAULT 'PENDING',  -- PENDING/PROCESSING/DONE/FAILED
    exif_orientation INT,                             -- 原图 EXIF 方向（1-8；空=无 EXIF，按不旋转处理）
    rotated        BOOLEAN        NOT NULL DEFAULT FALSE,      -- 是否已按 EXIF 方向摆正
    src_width      INT,                               -- 原图像素宽（EXIF 摆正前）
    src_height      INT,                              -- 原图像素高（EXIF 摆正前）
    process_cost_ms BIGINT,                           -- 后台处理耗时（毫秒），处理完成/失败均回填，耗时可见
    error_message  VARCHAR(500),                      -- FAILED 时的失败原因
    retry_count    INT            NOT NULL DEFAULT 0, -- 重试次数（手工重试/启动自愈累计）
    operator       VARCHAR(32),
    biz_time       TIMESTAMP,
    request_no     VARCHAR(64),
    version        INT            NOT NULL DEFAULT 0,
    create_by      BIGINT,
    create_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_handover_photo_hash UNIQUE (order_id, file_hash),
    CONSTRAINT ck_handover_photo_status CHECK (status IN ('PENDING', 'PROCESSING', 'DONE', 'FAILED'))
);

CREATE INDEX IF NOT EXISTS idx_handover_photo_order ON t_handover_photo (order_id);
CREATE INDEX IF NOT EXISTS idx_handover_photo_status ON t_handover_photo (status);
